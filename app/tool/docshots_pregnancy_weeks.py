#!/usr/bin/env python3
"""Generate lib/brands/balsm/docshots_pregnancy_weeks.dart.

Usage (from app/):
  python3 tool/docshots_pregnancy_weeks.py <Balsm-API-DotNet>/src/Balsm.API/Content/pregnancy-weeks.v1.json

The docs screenshots run on fake APIs (see docs/screenshots.md), so the weekly
pregnancy guidance has to come from a fixture. This writes the API's real
content as the API serves it to the app, one document per language, so the
captures show production copy and artwork:

- every {"en": ..., "ar": ...} text becomes the one string in that language
  (the server's `PregnancyWeeksFile.In`);
- media renditions made for another locale are dropped (`MediaEntry.In`);
- `language` is added.

Re-run it when the content file changes, then recapture.
"""

import json
import sys
from pathlib import Path

LANGUAGES = ("en", "ar")
OUT = Path(__file__).resolve().parent.parent / "lib/brands/balsm/docshots_pregnancy_weeks.dart"


def localized(value):
    return isinstance(value, dict) and set(value) == set(LANGUAGES)


def project(value, lang):
    if localized(value):
        return value[lang]
    if isinstance(value, dict):
        out = {k: project(v, lang) for k, v in value.items()}
        if "renditions" in out and "kind" in out:
            out["renditions"] = [r for r in out["renditions"] if r.get("when", {}).get("locale", lang) == lang]
        return out
    if isinstance(value, list):
        return [project(v, lang) for v in value]
    return value


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    docs = {}
    for lang in LANGUAGES:
        doc = {"language": lang, **project(source, lang)}
        text = json.dumps(doc, ensure_ascii=False, separators=(",", ":"))
        if "'''" in text:
            sys.exit("content contains ''' and cannot be embedded in a Dart string")
        # A plain multi-line string: escape what Dart would interpret.
        docs[lang] = text.replace("\\", "\\\\").replace("$", "\\$")
    entries = "\n".join(f"  '{lang}': '''{docs[lang]}''',\n" for lang in LANGUAGES)
    OUT.write_text(
        "// GENERATED by tool/docshots_pregnancy_weeks.py from the API's\n"
        f"// pregnancy-weeks.v1.json (version {source['version']}). Do not edit.\n"
        "//\n"
        "// The weekly pregnancy guidance as the API serves it, per language, for\n"
        "// the docs screenshots (fake APIs). Referenced only by main_docshots.dart,\n"
        "// so it is tree-shaken out of shipped builds. General guidance, not PHI.\n"
        "\n"
        "/// The `GET /api/v1/content/pregnancy-weeks` body (`data`), by language.\n"
        "const docshotsPregnancyWeeksJson = <String, String>{\n"
        f"{entries}"
        "};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.name}: version {source['version']}, {len(source['weeks'])} weeks")


if __name__ == "__main__":
    main()
