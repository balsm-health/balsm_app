import 'dart:io';

import 'package:core/core.dart';
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';

import 'schema_snapshot.dart';

/// Writes the current on-device schema as the frozen fixture of a release.
///
/// Not a check: it does nothing unless asked. Run it from `packages/core`
/// when a version ships, so later builds are tested against what that
/// version left on patients' phones:
///
///     BALSM_FREEZE_DB_SCHEMA=0.8.0 fvm flutter test test/upgrade/freeze_db_schema_test.dart
///
/// Commit the new `test/upgrade/fixtures/db/<version>.sql`. Never edit an
/// existing fixture: it is a record of what shipped.
void main() {
  final version = Platform.environment['BALSM_FREEZE_DB_SCHEMA'];

  test('freeze the current schema as a release fixture', () async {
    final db = AppDatabase(NativeDatabase.memory());
    addTearDown(db.close);
    final sql = await dumpSchemaSql(db);
    final file = File('${dbFixturesDir.path}/$version.sql');
    if (file.existsSync()) fail('${file.path} already exists; a shipped schema is never rewritten');
    file.writeAsStringSync('-- On-device schema as shipped in $version. Generated by\n'
        '-- freeze_db_schema_test.dart; do not edit.\n\n$sql\n');
  }, skip: version == null ? 'set BALSM_FREEZE_DB_SCHEMA=<version> to write a fixture' : null);
}
