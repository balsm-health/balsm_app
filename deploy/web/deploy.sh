#!/usr/bin/env bash
# Build the web app for one environment and deploy it to that environment's
# host.
#
#   deploy/web/deploy.sh staging            # app-stg.balsm.health
#   deploy/web/deploy.sh prod               # app.balsm.health
#   deploy/web/deploy.sh staging --dry-run  # build and print, deploy nothing
#
# The host comes from one place: HOST_SUFFIX in app/env/<brand>/<env>.json.
# With a suffix, it is appended to the Worker name and to the first label of
# every host in the brand's wrangler config (balsm-app-web-stg on
# app-stg.balsm.health). With none, the config is deployed as written, which
# is production. Building and deploying in one step is the point: app/build/web
# holds one build at a time, and this never ships one environment's build to
# another's host.
set -euo pipefail

env="${1:?usage: deploy/web/deploy.sh <env> [--brand=<brand>] [--dry-run]}"
shift
brand=balsm
dry_run=false
for arg in "$@"; do
  case "$arg" in
    --brand=*) brand="${arg#--brand=}" ;;
    --dry-run) dry_run=true ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
here="$root/deploy/web"
env_file="$root/app/env/$brand/$env.json"
base="$here/wrangler.jsonc"
[[ "$brand" == balsm ]] || base="$here/wrangler.$brand.jsonc"
[[ -f "$env_file" ]] || { echo "no $env_file" >&2; exit 1; }
[[ -f "$base" ]] || { echo "no $base" >&2; exit 1; }

suffix="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("HOST_SUFFIX",""))' "$env_file")"
if [[ -n "$suffix" && ! "$suffix" =~ ^[a-z0-9]+$ ]]; then
  echo "HOST_SUFFIX must be lowercase letters and digits, got: $suffix" >&2
  exit 1
fi
# The other way round is the dangerous one: a build that is not production
# landing on the production host.
if [[ -z "$suffix" && "$env" != prod ]]; then
  echo "$env_file has no HOST_SUFFIX, so this would deploy a $env build to the production host." >&2
  exit 1
fi

config="$base"
if [[ -n "$suffix" ]]; then
  config="$here/.wrangler.$brand.$suffix.jsonc"
  python3 - "$base" "$config" "$suffix" <<'PY'
import re, sys
src, dst, suffix = sys.argv[1:]
text = open(src, encoding="utf-8").read()
text, names = re.subn(r'("name":\s*")([^"]+)(")', rf'\g<1>\g<2>-{suffix}\g<3>', text, count=1)
text, hosts = re.subn(r'("pattern":\s*")([a-z0-9]+)(\.[^"]+")', rf'\g<1>\g<2>-{suffix}\g<3>', text)
if names != 1 or hosts < 1:
    sys.exit(f"{src}: expected one Worker name and at least one route pattern")
open(dst, "w", encoding="utf-8").write(f"// GENERATED by deploy/web/deploy.sh from {src.rsplit('/', 1)[-1]} — do not edit.\n" + text)
PY
fi

echo "deploy: $brand $env → $(grep -o '"pattern": *"[^"]*"' "$config" | cut -d'"' -f4 | tr '\n' ' ')($(grep -o '"name": *"[^"]*"' "$config" | head -1 | cut -d'"' -f4))"

"$root/bin/balsm" web "$brand" "$env" --base-href=/

if [[ "$dry_run" == true ]]; then
  echo "deploy: --dry-run, nothing deployed. Config: $config"
  exit 0
fi
npx --yes wrangler@4 deploy -c "$config"
